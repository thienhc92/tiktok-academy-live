import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {SQLiteTempleRepository} from './repository.ts';
import {TikTokConnector} from './connector.ts';
import {createGateway} from './gateway.ts';
const origin=process.env.TRIAL_ORIGIN??'http://127.0.0.1:3001';
const bind=process.env.LIVE_BIND_HOST??'127.0.0.1';
const port=Number(process.env.PORT??3002),gatewayKey=process.env.LIVE_GATEWAY_KEY;
if(!['127.0.0.1','0.0.0.0'].includes(bind)||!Number.isInteger(port)||port<1||port>65535)throw Error('Invalid listener configuration');
if(bind==='0.0.0.0'&&(!origin.startsWith('https:')||!gatewayKey||gatewayKey.length<32||(process.env.TRIAL_ADMIN_PASSWORD??'').length<16))throw Error('Public binding requires HTTPS origin and server secrets');
const folder=resolve(process.env.TRIAL_DATA_DIR??fileURLToPath(new URL('./data/',import.meta.url)));mkdirSync(folder,{recursive:true,mode:0o700});
const repository=new SQLiteTempleRepository(resolve(folder,'live.sqlite'));
const diagnostics=new Map<string,number>();
const gateway=createGateway({origin,password:process.env.TRIAL_ADMIN_PASSWORD??'',repository,gatewayKey,connector:()=>new TikTokConnector(code=>{if(Date.now()-(diagnostics.get(code)??0)>10000){diagnostics.set(code,Date.now());console.warn('[TikTok]',code);}})});
gateway.http.listen(port,bind,()=>console.info('TikTok backend ready. No TikTok connection until an authenticated Connect request.'));
let closing=false;const stop=async()=>{if(closing)return;closing=true;await gateway.close();repository.close();process.exit(0);};process.on('SIGINT',()=>void stop());process.on('SIGTERM',()=>void stop());
